    h.expect(g2).toBe(g1)
    h.expect(countClass(stroke, "UIGradient")).toBe(1)
    h.expect(g2.Transparency.keypoints[1].Value).toBe(FX.light.edgeTop)
    h.expect(g2.Transparency.keypoints[2].Value).toBe(FX.light.edgeBottom)
  end)
