h.describe("effects.lift", function()
  local function placed()
    local t, p = themed(), frame()
    local host = frame(); host.Parent = p
    host.AnchorPoint = rb.Vector2.new(0.5, 0.5)
    host.Position = rb.UDim2.new(0.5, 0, 0.5, 0); host.Size = rb.UDim2.new(0, 400, 0, 300)
    local s = Effects.shadow(p, t, { name = "WindowShadow", level = "window", zIndex = 0 })
    Effects.mirror(s, host, "window", t) -- rest 456 x 356
    return t, s, host
  end
  h.it("on: tweens Size +2*spreadDelta and alpha shadow+alphaDelta over Motion.fast; off: back to rest", function()
    local t, s = placed()
    h.mock.resetTweens()
    Effects.lift(s, t, true)
    local tw = h.mock.lastTween
    h.expect(tw.Instance).toBe(s)
    h.expect(tw.Info.Time).toBe(Theme.Motion.fast)
    h.expect(tw.Goal.Size.X.Offset).toBe(456 + 16); h.expect(tw.Goal.Size.Y.Offset).toBe(356 + 16)
    h.expect(tw.Goal.ImageTransparency).toBeCloseTo(FX.dark.shadow + Theme.Effect.lift.alphaDelta)
    Effects.lift(s, t, false)
    tw = h.mock.lastTween
    h.expect(tw.Goal.Size.X.Offset).toBe(456); h.expect(tw.Goal.Size.Y.Offset).toBe(356)
    h.expect(tw.Goal.ImageTransparency).toBe(FX.dark.shadow)
    h.expect(#h.mock.tweensFor(s)).toBe(2)
  end)
  h.it("mirror while lifted keeps the lift spread (drag calls mirror every frame)", function()
    local t, s, host = placed()
    Effects.lift(s, t, true)
    host.Size = rb.UDim2.new(0, 500, 0, 300)
    Effects.mirror(s, host, "window", t)
    h.expect(s.Size.X.Offset).toBe(556 + 16); h.expect(s.Size.Y.Offset).toBe(356 + 16)
    Effects.lift(s, t, false)
    h.expect(s.Size.X.Offset).toBe(556); h.expect(s.Size.Y.Offset).toBe(356)
  end)
  h.it("a shadow lifted before any placement grows from its current Size and returns to it", function()
    local t = themed()
    local s = Effects.shadow(frame(), t, { name = "S", zIndex = 0 })
    s.Size = rb.UDim2.new(0, 100, 0, 40)
    Effects.lift(s, t, true)
    h.expect(s.Size.X.Offset).toBe(116); h.expect(s.Size.Y.Offset).toBe(56)
    Effects.lift(s, t, false)
    h.expect(s.Size.X.Offset).toBe(100); h.expect(s.Size.Y.Offset).toBe(40)
  end)
  h.it("applies instantly with no tween under reduced motion", function()
    h.withReducedMotion(R, function()
      local t, s = placed()
      h.mock.resetTweens()
      Effects.lift(s, t, true)
      h.expect(h.mock.tweenCount()).toBe(0)
      h.expect(s.Size.X.Offset).toBe(456 + 16)
      h.expect(s.ImageTransparency).toBeCloseTo(FX.dark.shadow + Theme.Effect.lift.alphaDelta)
    end)
  end)
end)

h.describe("effects.reskin", function()
  h.it("shadow: re-applies the mode alpha, keeping the lift delta while lifted", function()
    local t = themed()
    local s = Effects.shadow(frame(), t, { name = "S", zIndex = 0 })
    Theme.applyMode(t, "light")
    Effects.reskin(s, t, "shadow")
    h.expect(s.ImageTransparency).toBe(FX.light.shadow)
    Effects.lift(s, t, true)
    Theme.applyMode(t, "dark")
    Effects.reskin(s, t) -- kind remembered from creation
    h.expect(s.ImageTransparency).toBeCloseTo(FX.dark.shadow + Theme.Effect.lift.alphaDelta)
  end)
  h.it("glow: swaps the tint token by identity; a hidden glow stays hidden, a shown one takes the mode alpha", function()
    desktop()
    local t = themed()
    local g = Effects.glow(frame(), t, t.Colors.primary, "control", 1)
    local accent = rb.Color3.fromRGB(59, 130, 246)
    Effects.reskin(g, t, "glow", accent)
    h.expect(g.ImageColor3).toBe(accent)
    h.expect(g.ImageTransparency).toBe(1)
    g.ImageTransparency = FX.dark.glow
    Theme.applyMode(t, "light")
    Effects.reskin(g, t, "glow")
    h.expect(g.ImageColor3).toBe(accent) -- token remembered from the previous reskin
    h.expect(g.ImageTransparency).toBe(FX.light.glow)
  end)
  h.it("rim: accepts the stroke or its gradient and never adds a second gradient", function()
    local t = themed()
    local stroke = Create.stroke(t.Colors.border, 1)
    local g = Effects.rim(stroke, t)
    Theme.applyMode(t, "light")
    Effects.reskin(stroke, t, "rim")
    h.expect(g.Transparency.keypoints[2].Value).toBe(FX.light.edgeBottom)
    Theme.applyMode(t, "dark")
    Effects.reskin(g, t, "rim")
    h.expect(g.Transparency.keypoints[2].Value).toBe(FX.dark.edgeBottom)
    h.expect(countClass(stroke, "UIGradient")).toBe(1)
  end)
  h.it("throws on an unknown kind", function()
    h.expect(function() Effects.reskin(frame(), themed(), "halo") end).toThrow("kind")
  end)
end)

h.describe("effects.skeleton", function()
  h.it("builds a surface block with a corner and one looping Linear shimmer gradient", function()
    local t, p = Theme.new(), frame()
    h.mock.resetTweens()
    local sk = Effects.skeleton(p, t, { size = rb.UDim2.new(1, 0, 0, 20), radius = 4 })
    local f = sk.Frame
    h.expect(f.ClassName).toBe("Frame")
    h.expect(f.Parent).toBe(p)
    h.expect(f.BackgroundColor3).toBe(t.Colors.surface)
    h.expect(f.Size.Y.Offset).toBe(20)
    h.expect(f:FindFirstChildOfClass("UICorner").CornerRadius.Offset).toBe(4)
    local g = f:FindFirstChildOfClass("UIGradient")
    h.expect(g).toBe(sk.Gradient)
    h.expect(g.Rotation).toBe(15)
    h.expect(g.Color.color[1].Value.R).toBe(1)
    h.expect(g.Color.color[2].Value).toBe(FX.dark.inset)
    h.expect(g.Color.color[3].Value.R).toBe(1)
    local tws = h.mock.tweensFor(g)
    h.expect(#tws).toBe(1)
    h.expect(tws[1].Info.RepeatCount).toBe(-1)
    h.expect(tws[1].Info.Reverses).toBe(false)
    h.expect(tws[1].Info.EasingStyle.Name).toBe("Linear")
    h.expect(tws[1].Info.Time).toBe(1.1)
    h.expect(tws[1].Goal.Offset.X).toBe(1); h.expect(tws[1].Goal.Offset.Y).toBe(0)
  end)
  h.it("Stop cancels the loop, fades the block out and destroys it (idempotent)", function()
    local t, p = Theme.new(), frame()
    h.mock.resetTweens()
    local sk = Effects.skeleton(p, t, { size = rb.UDim2.new(1, 0, 0, 20) })
    local loopTw = h.mock.tweensFor(sk.Gradient)[1]
    sk.Stop()
    h.expect(loopTw.cancelled).toBe(true)
    local fade = h.mock.lastTween
    h.expect(fade.Instance).toBe(sk.Frame)
    h.expect(fade.Goal.BackgroundTransparency).toBe(1)
    h.expect(fade.Info.Time).toBe(Theme.Motion.exit)
    h.expect(sk.Frame.Parent).toBeNil()
    h.expect(p:FindFirstChild("Skeleton")).toBeNil()
    local n = h.mock.tweenCount()
    sk.Stop()
    h.expect(h.mock.tweenCount()).toBe(n)
  end)
  h.it("honours the light inset band, opts.band and an Effect.skeleton token group when present", function()
    local light = Theme.applyMode(Theme.new(), "light")
    h.expect(Effects.skeleton(frame(), light, {}).Gradient.Color.color[2].Value).toBe(FX.light.inset)
    local band = rb.Color3.fromRGB(1, 2, 3)
    h.expect(Effects.skeleton(frame(), light, { band = band }).Gradient.Color.color[2].Value).toBe(band)
    local t = Theme.new({ Effect = { skeleton = { period = 2, rotation = 30 } } })
    h.mock.resetTweens()
    local sk = Effects.skeleton(frame(), t, {})
    h.expect(sk.Gradient.Rotation).toBe(30)
    h.expect(h.mock.lastTween.Info.Time).toBe(2)
  end)
  h.it("is a static block under reduced motion: no tween, Stop destroys immediately", function()
    h.withReducedMotion(R, function()
      local p = frame()
      h.mock.resetTweens()
      local sk = Effects.skeleton(p, Theme.new(), { size = rb.UDim2.new(1, 0, 0, 20) })
      h.expect(h.mock.tweenCount()).toBe(0)
      h.expect(sk.Frame.Parent).toBe(p)
      sk.Stop()
      h.expect(h.mock.tweenCount()).toBe(0)
      h.expect(sk.Frame.Parent).toBeNil()
    end)
  end)
end)

