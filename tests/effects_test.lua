local h = require("tests.helper")
local R = h.loadLib()
local Effects, Theme, Animate, Create = R.Effects, R.Theme, R.Animate, R.Create
local rb = h.roblox
local FX = Theme.MODE_EFFECTS
local SHADOW = "rbxassetid://1"

-- A theme with the 9-slice asset filled in (the default '' keeps every layer nil).
local function themed(mode, effect)
  local over = { shadowId = SHADOW }
  for k, v in pairs(effect or {}) do over[k] = v end
  local t = Theme.new({ Effect = over })
  if mode then Theme.applyMode(t, mode) end
  return t
end
local function frame() return rb.Instance.new("Frame") end
local function countClass(inst, cls)
  local n = 0
  for _, c in ipairs(inst:GetChildren()) do if c.ClassName == cls then n = n + 1 end end
  return n
end
-- Form-factor switches mirror tests/device_test.lua: touch-only + phone aspect = Mobile.
local function desktop()
  local uis, cam = rb.game:GetService("UserInputService"), rb.workspace.CurrentCamera
  uis.TouchEnabled = false; uis.MouseEnabled = true; h.mock.tenFoot = false
  cam.ViewportSize = rb.Vector2.new(1280, 720)
end
local function mobile()
  local uis, cam = rb.game:GetService("UserInputService"), rb.workspace.CurrentCamera
  uis.TouchEnabled = true; uis.MouseEnabled = false; h.mock.tenFoot = false
  cam.ViewportSize = rb.Vector2.new(320, 640)
end

