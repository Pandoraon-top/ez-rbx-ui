h.describe("effects.follow", function()
  h.it("skips the sync while Absolute* is nil and returns a maid-compatible handle", function()
    local t, p = themed(), frame()
    local host = frame(); host.Parent = p
    local s = Effects.shadow(p, t, { name = "DialogShadow", zIndex = 0 })
    local hd = Effects.follow(s, host, "dialog", t)
    h.expect(type(hd.Disconnect)).toBe("function")
    h.expect(s.Size).toBeNil(); h.expect(s.Position).toBeNil()
    host:GetPropertyChangedSignal("AbsoluteSize"):Fire()
    h.expect(s.Size).toBeNil()
  end)
  h.it("syncs after the test sets Absolute* and fires the property signal", function()
    local t, p = themed(), frame()
    local host = frame(); host.Parent = p
    local s = Effects.shadow(p, t, { name = "DialogShadow", zIndex = 0 })
    Effects.follow(s, host, "dialog", t) -- dialog: spread 32, offsetY 10
    host.AbsoluteSize = rb.Vector2.new(200, 100)
    host.AbsolutePosition = rb.Vector2.new(30, 40)
    host:GetPropertyChangedSignal("AbsoluteSize"):Fire()
    h.expect(s.Size.X.Offset).toBe(264); h.expect(s.Size.Y.Offset).toBe(164)
    h.expect(s.Position.X.Offset).toBe(130); h.expect(s.Position.Y.Offset).toBe(100)
    host.AbsolutePosition = rb.Vector2.new(50, 40)
    host:GetPropertyChangedSignal("AbsolutePosition"):Fire()
    h.expect(s.Position.X.Offset).toBe(150)
  end)
  h.it("subtracts the shared parent's screen origin so the shadow lands in local space", function()
    local t, p = themed(), frame()
    p.AbsolutePosition = rb.Vector2.new(0, 36)
    local host = frame(); host.Parent = p
    host.AbsoluteSize = rb.Vector2.new(100, 100); host.AbsolutePosition = rb.Vector2.new(10, 46)
    local s = Effects.shadow(p, t, { name = "DialogShadow", zIndex = 0 })
    Effects.follow(s, host, "dialog", t) -- initial sync runs when geometry already exists
    h.expect(s.Position.X.Offset).toBe(60); h.expect(s.Position.Y.Offset).toBe(70)
  end)
  h.it("gives its connections to the maid; after cleanup the signal no longer syncs", function()
    local t, p = themed(), frame()
    local host = frame(); host.Parent = p
    local s = Effects.shadow(p, t, { name = "DialogShadow", zIndex = 0 })
    local maid = R.Maid.new()
    Effects.follow(s, host, "dialog", t, maid)
    maid:DoCleanup()
    host.AbsoluteSize = rb.Vector2.new(200, 100); host.AbsolutePosition = rb.Vector2.new(0, 0)
    host:GetPropertyChangedSignal("AbsoluteSize"):Fire()
    host:GetPropertyChangedSignal("AbsolutePosition"):Fire()
    h.expect(s.Size).toBeNil()
  end)
end)

h.describe("effects.rim", function()
  h.it("adds exactly one UIGradient under the stroke with Rotation 90 and the dark edge alphas", function()
    local t, p = themed(), frame()
    local color = t.Colors.border
    local stroke = Create.stroke(color, 1); stroke.Parent = p
    local g = Effects.rim(stroke, t)
    h.expect(g.ClassName).toBe("UIGradient")
    h.expect(g.Parent).toBe(stroke)
    h.expect(g.Rotation).toBe(90)
    h.expect(g.Transparency.keypoints[1].Time).toBe(0)
