    h.expect(s.Position.X.Offset).toBe(122); h.expect(s.Position.Y.Offset).toBe(72)
  end)
  h.it("mirror falls back to the level given at creation and skips a host without geometry", function()
    local t, p = themed(), frame()
    local s = Effects.shadow(p, t, { name = "S", level = "tooltip" }) -- spread 10, offsetY 2
    local bare = frame()
    h.expect(Effects.mirror(s, bare, nil, t)).toBe(s)
    h.expect(s.Size).toBeNil()
    local host = frame(); host.Position = rb.UDim2.new(0, 0, 0, 0); host.Size = rb.UDim2.new(0, 20, 0, 10)
