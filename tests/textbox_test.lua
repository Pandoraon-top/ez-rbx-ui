  -- ---- visual-polish phase 2 (2.15 shake/fade/copy, 2.7 inline buttons, 2.8 disabled) ----
  h.it("SetInvalid shakes the box on its own X and ends exactly where it started (2.15)", function()
    local tb = TextBox.new({ Parent = Create("Frame", {}), Text = "Key", FullWidth = true })
    local box = tb.Frame:FindFirstChild("Box")
    local x0 = box.Position.X.Offset
    h.mock.resetTweens()
    tb.SetInvalid("Required")
    local sh = R.Theme.Motion.shake
    local tws = h.mock.tweensFor(box)
    h.expect(#tws).toBe(sh.steps + 1)                   -- Motion.shake.steps + the closing return
    h.expect(tws[1].Info.Time).toBe(sh.step)
    h.expect(tws[1].Info.EasingStyle).toBe(h.roblox.Enum.EasingStyle.Sine)
    h.expect(tws[1].Goal.Position.X.Offset).toBe(x0 + sh.amp)
    h.expect(tws[2].Goal.Position.X.Offset).toBe(x0 - sh.amp)
    h.expect(tws[#tws].Goal.Position.X.Offset).toBe(x0)
    h.expect(box.Position.X.Offset).toBe(x0)
    h.expect(box.Position.Y.Offset).toBe(tws[1].Goal.Position.Y.Offset)  -- horizontal only
  end)
  h.it("SetInvalid fades the error in and eases the row; SetValid fades out then hides (2.15)", function()
    local tb = TextBox.new({ Parent = Create("Frame", {}), Text = "Key", FullWidth = true })
    local baseH = tb.Frame.Size.Y.Offset
    tb.SetInvalid("Required")
    local msg = tb.Frame:FindFirstChild("Error")
    h.expect(msg.Visible).toBe(true)                    -- Visible is synchronous, the fade is not
    h.expect(msg.TextTransparency).toBe(0)
    h.expect(tb.Frame.Size.Y.Offset).toBe(baseH + 18)   -- ERROR_H
    local rowTws = h.mock.tweensFor(tb.Frame)
    h.expect(rowTws[#rowTws].Info.Time).toBe(R.Theme.Motion.base)
    local msgTws = h.mock.tweensFor(msg)
    h.expect(msgTws[#msgTws].Goal.TextTransparency).toBe(0)
    tb.SetValid()
    h.expect(msg.TextTransparency).toBe(1)
    h.expect(msg.Visible).toBe(false)                   -- hidden once the fade completes
    h.expect(tb.Frame.Size.Y.Offset).toBe(baseH)
    local out = h.mock.tweensFor(msg)
    h.expect(out[#out].Info.Time).toBe(R.Theme.Motion.fast)
  end)
