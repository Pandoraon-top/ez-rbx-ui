      Buttons = { { Text = "Send", Variant = "default", Callback = function(text) got = text end } } })
    local box = tb.Frame:FindFirstChild("Box")
    local btn = box:FindFirstChild("Button1")
    h.expect(btn ~= nil).toBeTruthy()
