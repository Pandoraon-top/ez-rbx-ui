h.describe("animate.popIn/popOut", function()
  h.it("popIn('down') grows a UIScale from exitScale (Back/Out, base) and slides up into place (Quart/Out, fast)", function()
    local f = frameAt(10, 20)
    h.mock.resetTweens()
    local from = captureFrom(function() Animate.popIn(f, "down") end)
    local us = f:FindFirstChildOfClass("UIScale")
    h.expect(us ~= nil).toBeTruthy()
    local scaleTw = h.mock.tweensFor(us)[1]
    local posTw = h.mock.tweensFor(f)[1]
    h.expect(scaleTw ~= nil).toBeTruthy()
    h.expect(posTw ~= nil).toBeTruthy()
    h.expect(scaleTw.Goal.Scale).toBe(1)
    h.expect(scaleTw.Info.EasingStyle.Name).toBe("Back")
    h.expect(scaleTw.Info.EasingDirection.Name).toBe("Out")
    h.expect(scaleTw.Info.Time).toBe(0.18)
    h.expect(posTw.Info.EasingStyle.Name).toBe("Quart")
    h.expect(posTw.Info.EasingDirection.Name).toBe("Out")
    h.expect(posTw.Info.Time).toBe(0.12)
    -- pre-set "from" state: scale exitScale, Position nudged popSlide px above the target
    local fromScale, fromPos
    for _, s in ipairs(from) do
      if s.Instance == us then fromScale = s.From.Scale end
      if s.Instance == f then fromPos = s.From.Position end
    end
    h.expect(fromScale).toBeCloseTo(EXIT_SCALE)
    h.expect(fromPos.Y.Offset).toBe(20 - POP_SLIDE)
    h.expect(fromPos.X.Offset).toBe(10)
    -- final state is the caller's Position (layout code reads it synchronously)
    h.expect(us.Scale).toBe(1)
    h.expect(f.Position.X.Offset).toBe(10)
    h.expect(f.Position.Y.Offset).toBe(20)
  end)
  h.it("popIn('up') starts popSlide px below the target; nil edge behaves like 'down'", function()
