    local fromPos
    for _, s in ipairs(from) do if s.Instance == f then fromPos = s.From.Position end end
    h.expect(fromPos.Y.Offset).toBe(100 + POP_SLIDE)
    h.expect(f.Position.Y.Offset).toBe(100)
    local g = frameAt(0, 100)
    from = captureFrom(function() Animate.popIn(g) end)
    for _, s in ipairs(from) do if s.Instance == g then fromPos = s.From.Position end end
    h.expect(fromPos.Y.Offset).toBe(100 - POP_SLIDE)
  end)
  h.it("popIn reuses an existing UIScale instead of adding a second one", function()
