local R = h.loadLib()
local Theme = R.Theme
local Motion = Theme.Motion
-- F1 lands the new Motion tokens in parallel; read them through the same fallbacks animate.lua
-- uses so this file is green before and after that edit.
local SPIN, EXIT, EXIT_SCALE, POP_SLIDE = Motion.spin or 0.8, Motion.exit or 0.14, Motion.exitScale or 0.96, Motion.popSlide or 6

-- A fresh copy of core/animate.lua (bypasses the requireModule cache) so the explicit
-- reduced-motion flag can be observed from its pristine state, independent of test order.
local function freshAnimate()
  local chunk = assert(loadfile("core/animate.lua"))
  setfenv(chunk, setmetatable({}, { __index = function(_, k)
    if h.roblox[k] ~= nil then return h.roblox[k] end
    return _G[k]
  end }))
  local A = chunk()
  A.Init({ Theme = Theme })
  return A
end

-- Snapshot each tweened property at Create time (before the synchronous mock Play overwrites it
-- with the goal) so a recipe's pre-set "from" state can be asserted, not just its goal.
local function captureFrom(fn)
  local TS = h.roblox.game:GetService("TweenService")
  local orig = TS.Create
  local from = {}
  TS.Create = function(self, inst, info, goal)
    local snap = {}
    for k in pairs(goal) do snap[k] = inst[k] end
    from[#from + 1] = { Instance = inst, From = snap }
    return orig(self, inst, info, goal)
  end
  local ok, err = pcall(fn)
  TS.Create = orig
  if not ok then error(err, 0) end
  return from
end

local function frameAt(xo, yo)
  local f = h.roblox.Instance.new("Frame")
  f.Position = h.roblox.UDim2.new(0, xo, 0, yo)
  return f
end

