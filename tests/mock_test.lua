h.describe("mock TweenInfo", function()
  h.it("captures all six args with Roblox defaults", function()
    local TI = h.roblox.TweenInfo
    local i3 = TI.new(0.2, Enum.EasingStyle.Quad, Enum.EasingDirection.Out)
    h.expect(i3.Time).toBe(0.2)
    h.expect(i3.RepeatCount).toBe(0); h.expect(i3.Reverses).toBe(false); h.expect(i3.DelayTime).toBe(0)
    local loop = TI.new(0.8, Enum.EasingStyle.Linear, Enum.EasingDirection.InOut, -1)
    h.expect(loop.RepeatCount).toBe(-1)
    local full = TI.new(0.3, Enum.EasingStyle.Back, Enum.EasingDirection.In, 2, true, 0.1)
    h.expect(full.RepeatCount).toBe(2); h.expect(full.Reverses).toBe(true); h.expect(full.DelayTime).toBe(0.1)
    local d = TI.new()
    h.expect(d.Time).toBe(1)
    h.expect(d.EasingStyle).toBe(Enum.EasingStyle.Quad)
    h.expect(d.EasingDirection).toBe(Enum.EasingDirection.Out)
  end)
  h.it("strict mode rejects nil numeric slots like Roblox but tolerates a trailing nil style", function()
    local TI = h.roblox.TweenInfo
    withStrict(function()
      h.expect(function() TI.new(nil) end).toThrow("invalid argument #1 to 'new' (number expected, got nil)")
      h.expect(function() TI.new(0.2, Enum.EasingStyle.Quad, Enum.EasingDirection.Out, 0, false, nil) end)
        .toThrow("invalid argument #6 to 'new' (number expected, got nil)")
      h.expect(function() TI.new(0.2, nil, Enum.EasingDirection.Out) end).toThrow("#2")
      h.expect(function() TI.new(0.2, Enum.EasingStyle.Quad, nil, 0) end).toThrow("#3")
      h.expect(function() TI.new(0.2, Enum.EasingStyle.Quad, Enum.EasingDirection.Out, "x") end).toThrow("#4")
      h.expect(function() TI.new(0.2, Enum.EasingStyle.Quad, Enum.EasingDirection.Out, 0, nil, 0.1) end).toThrow("#5")
      h.expect(TI.new(0.2, nil).Time).toBe(0.2)
      h.expect(TI.new(0.8, Enum.EasingStyle.Linear, Enum.EasingDirection.InOut, -1).RepeatCount).toBe(-1)
      h.expect(TI.new(0.3, Enum.EasingStyle.Quad, Enum.EasingDirection.Out, 0, false, 0.05).DelayTime).toBe(0.05)
    end)
    h.expect(TI.new(nil).Time).toBe(1) -- lenient mode keeps today's forgiveness
  end)
end)

h.describe("mock TweenService capture", function()
  h.it("records every Create in mock.tweens with per-instance lookup", function()
    local TS = h.roblox.game:GetService("TweenService")
    h.mock.resetTweens()
    local a, b = Instance.new("Frame"), Instance.new("Frame")
    TS:Create(a, h.roblox.TweenInfo.new(0.1), { Rotation = 10 })
    local t2 = TS:Create(b, h.roblox.TweenInfo.new(0.1), { Rotation = 20 })
    local t3 = TS:Create(a, h.roblox.TweenInfo.new(0.1), { Rotation = 30 })
    h.expect(h.mock.tweenCount()).toBe(3)
    h.expect(h.mock.lastTween).toBe(t3)
    h.expect(h.mock.tweensFor(a)).toHaveLength(2)
    h.expect(h.mock.tweensFor(b)[1]).toBe(t2)
    h.mock.resetTweens()
    h.expect(h.mock.tweenCount()).toBe(0)
    h.expect(h.mock.lastTween).toBeNil()
  end)
  h.it("Play is synchronous even for RepeatCount -1; Cancel/Pause only set flags", function()
    local TS = h.roblox.game:GetService("TweenService")
    local f = Instance.new("ImageLabel")
    local tw = TS:Create(f, h.roblox.TweenInfo.new(0.8, Enum.EasingStyle.Linear, Enum.EasingDirection.InOut, -1),
      { Rotation = 360 })
    local fired, state = 0, nil
    tw.Completed:Connect(function(s) fired = fired + 1; state = s end)
    h.expect(tw.PlaybackState).toBe(Enum.PlaybackState.Begin)
    tw:Play()
    h.expect(f.Rotation).toBe(360)
    h.expect(fired).toBe(1)
    h.expect(state).toBe(Enum.PlaybackState.Completed)
    h.expect(tw.played).toBeTruthy()
    h.expect(tw.cancelled).toBe(false)
    h.expect(tw.paused).toBe(false)
    tw:Pause(); h.expect(tw.paused).toBe(true); h.expect(tw.PlaybackState).toBe(Enum.PlaybackState.Paused)
    tw:Cancel(); h.expect(tw.cancelled).toBe(true); h.expect(tw.PlaybackState).toBe(Enum.PlaybackState.Cancelled)
    h.expect(fired).toBe(1) -- Cancel after a finished tween does not re-fire Completed
  end)
end)

