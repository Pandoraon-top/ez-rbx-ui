h.describe("mock strict allowlist", function()
  local function ok(cls, prop, v) local i = Instance.new(cls); i[prop] = v; h.expect(i[prop]).toBe(v) end
  local function rejects(cls, prop)
    h.expect(function() Instance.new(cls)[prop] = 1 end).toThrow(prop .. " is not a valid member of " .. cls)
  end
  h.it("shared properties stay valid on every owning class", function()
    withStrict(function()
      ok("Frame", "Rotation", 5); ok("ImageLabel", "Rotation", 5); ok("UIGradient", "Rotation", 90)
      rejects("UIStroke", "Rotation"); rejects("ScreenGui", "Rotation")
      ok("UIStroke", "Color", 1); ok("UIGradient", "Color", 1); rejects("Frame", "Color")
      ok("UIStroke", "Transparency", 0.3); ok("UIGradient", "Transparency", 1); rejects("ImageLabel", "Transparency")
      ok("UIGradient", "Offset", 1); rejects("Frame", "Offset"); rejects("UIStroke", "Offset")
      ok("Frame", "SelectionImageObject", 1); ok("TextButton", "SelectionImageObject", 1); rejects("UIStroke", "SelectionImageObject")
    end)
  end)
  h.it("single-owner properties reject every other class", function()
    withStrict(function()
      ok("UIStroke", "Thickness", 2); ok("UIStroke", "ApplyStrokeMode", 1); ok("UIStroke", "LineJoinMode", 1)
      rejects("Frame", "Thickness"); rejects("UIGradient", "ApplyStrokeMode")
      ok("CanvasGroup", "GroupTransparency", 0.5); ok("CanvasGroup", "GroupColor3", 1); rejects("Frame", "GroupTransparency")
      ok("UIScale", "Scale", 0.9); rejects("Frame", "Scale"); rejects("UIStroke", "Scale")
      ok("ScrollingFrame", "CanvasSize", 1); ok("ScrollingFrame", "CanvasPosition", 1); ok("ScrollingFrame", "ScrollBarThickness", 4)
      ok("ScrollingFrame", "ScrollBarImageTransparency", 1); ok("ScrollingFrame", "AutomaticCanvasSize", 1)
      rejects("Frame", "CanvasSize"); rejects("Frame", "ScrollBarThickness"); rejects("CanvasGroup", "CanvasPosition")
      ok("UICorner", "CornerRadius", 1); rejects("Frame", "CornerRadius")
      ok("UISizeConstraint", "MinSize", 1); ok("UISizeConstraint", "MaxSize", 1); rejects("Frame", "MinSize")
    end)
  end)
  h.it("keeps text/image/button rules and splits TextBox-only props", function()
    withStrict(function()
      ok("TextLabel", "Text", "x"); ok("TextButton", "TextSize", 12); ok("TextBox", "TextColor3", 1)
      rejects("Frame", "Text"); rejects("ImageLabel", "TextSize")
      for _, p in ipairs({ "PlaceholderText", "PlaceholderColor3", "ClearTextOnFocus", "TextEditable", "CursorPosition", "MultiLine" }) do
        ok("TextBox", p, 1); rejects("TextLabel", p); rejects("TextButton", p)
      end
      ok("ImageLabel", "Image", "rbx"); ok("ImageButton", "SliceCenter", 1); rejects("Frame", "Image"); rejects("TextLabel", "ImageColor3")
      ok("TextButton", "AutoButtonColor", false); ok("ImageButton", "Modal", true); rejects("TextLabel", "AutoButtonColor"); rejects("Frame", "Style")
      ok("Frame", "BackgroundColor3", 1); ok("UIStroke", "Enabled", true) -- unlisted props are never gated
    end)
  end)
  h.it("lenient mode stores everything so unit tests stay terse", function()
    h.expect(mockmod.strict).toBe(false)
    local f = Instance.new("Frame"); f.Thickness = 2; f.Text = "x"; f.CanvasSize = 1
    h.expect(f.Thickness).toBe(2)
  end)
end)

