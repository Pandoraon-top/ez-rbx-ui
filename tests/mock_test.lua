h.describe("mock timers", function()
  h.it("immediate mode runs task.delay synchronously; task.cancel is a no-op", function()
    h.expect(h.mock.timerMode).toBe("immediate")
    local ran
    local th = h.roblox.task.delay(5, function(a, b) ran = a + b end, 1, 2)
    h.expect(ran).toBe(3)
    h.expect(type(th)).toBe("thread")
    h.roblox.task.cancel(th)
    h.expect(h.mock.timerCount()).toBe(0)
  end)
  h.it("queued mode parks callbacks until mock.advance reaches their due time, in (due, insertion) order", function()
    local log = {}
    h.withQueuedTimers(function()
      local task = h.roblox.task
      task.delay(0.3, function() log[#log + 1] = "c" end)
      task.delay(0.1, function(x) log[#log + 1] = x end, "a")
      task.delay(0.1, function() log[#log + 1] = "b" end)
      local dead = task.delay(0.2, function() log[#log + 1] = "cancelled" end)
      h.expect(#log).toBe(0)
      h.expect(h.mock.timerCount()).toBe(4)
      task.cancel(dead)
      h.expect(h.mock.timerCount()).toBe(3)
      h.mock.advance(0.1)
      h.expect(table.concat(log, ",")).toBe("a,b")
      h.mock.advance(0.1) -- t=0.2: only the cancelled entry was due
      h.expect(table.concat(log, ",")).toBe("a,b")
      -- a callback may queue a follow-up; it runs in the same advance once due (after earlier-queued peers)
      task.delay(0.05, function() task.delay(0, function() log[#log + 1] = "nested" end) end)
      h.mock.advance(0.1)
      h.expect(table.concat(log, ",")).toBe("a,b,c,nested")
      h.expect(h.mock.timerCount()).toBe(0)
      h.expect(h.roblox.tick()).toBeCloseTo(0.3)
    end)
    h.expect(h.mock.timerMode).toBe("immediate")
    h.expect(#h.mock.timers).toBe(0)
  end)
  h.it("withQueuedTimers restores immediate mode and clears the queue when fn throws", function()
    h.expect(function()
      h.withQueuedTimers(function() h.roblox.task.delay(1, function() end); error("boom") end)
    end).toThrow("boom")
    h.expect(h.mock.timerMode).toBe("immediate")
    h.expect(#h.mock.timers).toBe(0)
  end)
end)

h.describe("mock Destroy", function()
  h.it("tears down the whole subtree, firing Destroying on each descendant once", function()
    local root, child, grand = Instance.new("Frame"), Instance.new("Frame"), Instance.new("TextLabel")
    child.Parent = root; grand.Parent = child
    local fired = {}
    child.Destroying:Connect(function() fired[#fired + 1] = "child" end)
    grand.Destroying:Connect(function() fired[#fired + 1] = "grand" end)
    root:Destroy()
    h.expect(root:GetChildren()).toHaveLength(0)
    h.expect(child:GetChildren()).toHaveLength(0)
    h.expect(child.Parent).toBeNil()
    h.expect(grand.Parent).toBeNil()
    h.expect(root._destroyed).toBe(true); h.expect(child._destroyed).toBe(true); h.expect(grand._destroyed).toBe(true)
    h.expect(table.concat(fired, ",")).toBe("child,grand")
    root:Destroy() -- second Destroy is a no-op, like Roblox
    h.expect(#fired).toBe(2)
  end)
  h.it("detaches the destroyed instance from its parent", function()
    local p, c = Instance.new("Frame"), Instance.new("Frame")
    c.Name = "C"; c.Parent = p
    c:Destroy()
    h.expect(p:FindFirstChild("C")).toBeNil()
    h.expect(p:GetChildren()).toHaveLength(0)
    h.expect(c.Parent).toBeNil()
  end)
end)

