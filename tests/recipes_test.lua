    h.expect(tw.Info.Time).toBe(theme.Motion.fast)
    Recipes.disabled(parts, false, theme)
    h.expect(surface.BackgroundTransparency).toBe(0)
    h.expect(label.TextTransparency).toBe(0.2)
    h.expect(icon.ImageTransparency).toBe(0) -- rest omitted: engine default 0
  end)
  h.it("skips nil parts (optional stroke) and applies instantly under reduced motion", function()
    local R, Recipes, theme = ctx()
    local surface = mk("Frame", "Surface")
    local ok = pcall(Recipes.disabled, { { nil, "Transparency", 0 }, { surface, "BackgroundTransparency", 0 } }, true, theme)
    h.expect(ok).toBe(true)
    h.expect(surface.BackgroundTransparency).toBe(theme.Opacity.disabled)
    h.withReducedMotion(R, function()
      h.mock.resetTweens()
      Recipes.disabled({ { surface, "BackgroundTransparency", 0 } }, false, theme)
      h.expect(surface.BackgroundTransparency).toBe(0)
      h.expect(h.mock.tweenCount()).toBe(0)
    end)
  end)
end)

